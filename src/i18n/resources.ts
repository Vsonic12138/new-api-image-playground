export const LANGUAGE_OPTIONS = [
  {code:'zhCN',label:'简体中文'}, {code:'en',label:'English'},
  {code:'fr',label:'Français'}, {code:'ru',label:'Русский'},
  {code:'ja',label:'日本語'}, {code:'vi',label:'Tiếng Việt'},
  {code:'zhTW',label:'繁體中文'},
] as const

export function normalizeLanguage(value: string): string {
  const v = value.toLowerCase().replaceAll('_','-')
  if (['zhtw','zh-tw','zh-hk','zh-mo'].includes(v) || v.startsWith('zh-hant')) return 'zhTW'
  if (v === 'zh' || v === 'zhcn' || v.startsWith('zh-hans') || v.startsWith('zh-cn')) return 'zhCN'
  return LANGUAGE_OPTIONS.find(l => l.code.toLowerCase() === v)?.code || v.split('-')[0]
}
export const toIntlLocale = (lang: string) => lang === 'zhCN' ? 'zh-CN' : lang === 'zhTW' ? 'zh-TW' : lang

